// Invoices, invoice line items, and the monthly billing run log.
// Phase 4 implements this domain.
//
// An invoice is the financial obligation created from a subscription plan. It is
// a debit in the subscriber's ledger. Invoices are NEVER deleted: a voided invoice
// keeps its row forever and is reversed by a credit ledger entry.
//
// Duplicate prevention is the whole point of this phase: the pair
// (service_account_id, billing_period_year, billing_period_month) identifies the one
// monthly invoice for a service account. The billing job checks for an existing
// invoice before inserting, inside a transaction that locks the account.
//
// Every monetary column is an integer number of centavos (PHP 999.00 = 99900).

import { relations, sql } from "drizzle-orm";
import {
  date,
  index,
  integer,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  varchar,
} from "drizzle-orm/pg-core";

import { serviceAccounts } from "./subscribers";
import { users } from "./users";

// ─── Invoice Status ───────────────────────────────────────────────────────────
// Mirrors INVOICE_STATUSES in the shared package; the strings must match exactly.
// `unpaid` is the stored spelling required by section 3.4; the API still accepts
// the old `posted` spelling as an input alias for one release (see the shared
// LEGACY_INVOICE_STATUS_ALIASES) but it is never stored.
export const invoiceStatusEnum = pgEnum("invoice_status", [
  "draft",
  "unpaid",
  "partially_paid",
  "paid",
  "void",
  "overdue",
  "credited",
]);

// ─── Invoice Type ─────────────────────────────────────────────────────────────
// Mirrors INVOICE_TYPES in the shared package.
export const invoiceTypeEnum = pgEnum("invoice_type", [
  "monthly_subscription", // Regular monthly bill generated by the billing job
  "reconnection_fee", // Charged when a suspended account is reconnected
  "installation_fee", // One-off fee charged when a new service account is installed
  "adjustment", // Manual correction (with justification)
  "late_fee", // Penalty for an overdue account
]);

// ─── Invoices ─────────────────────────────────────────────────────────────────
export const invoices = pgTable(
  "invoices",
  {
    id: uuid("id").primaryKey().defaultRandom(),

    // Human-readable invoice number — printed on documents.
    // Format: INV-YYYY-MM-XXXXXX (e.g. INV-2025-01-000042).
    invoiceNumber: varchar("invoice_number", { length: 30 }).notNull().unique(),

    serviceAccountId: uuid("service_account_id")
      .notNull()
      .references(() => serviceAccounts.id),

    invoiceType: invoiceTypeEnum("invoice_type").notNull(),
    status: invoiceStatusEnum("status").notNull().default("draft"),

    // The billing period this invoice covers (monthly subscriptions only).
    // year + month together identify the one monthly invoice per service account.
    // Null for one-off invoices such as a reconnection fee.
    billingPeriodYear: integer("billing_period_year"),
    billingPeriodMonth: integer("billing_period_month"),

    // Invoice dates
    invoiceDate: date("invoice_date").notNull(), // When the invoice was generated
    dueDate: date("due_date").notNull(), // When payment is due (e.g. the 15th)

    // Financial totals (all in centavos)
    subtotalCentavos: integer("subtotal_centavos").notNull(),
    lateFeesCentavos: integer("late_fees_centavos").notNull().default(0),
    totalAmountCentavos: integer("total_amount_centavos").notNull(), // subtotal + late fees
    paidAmountCentavos: integer("paid_amount_centavos").notNull().default(0),
    remainingBalanceCentavos: integer("remaining_balance_centavos").notNull(), // total - paid

    // For voided invoices: the ledger entry that reversed this invoice.
    // Kept as a plain id here to avoid a forward reference; the ledger row is the
    // source of truth and points back at the invoice.
    voidedByTransactionId: uuid("voided_by_transaction_id"),

    // Internal notes (reason for a manual adjustment, void reason, etc.)
    notes: text("notes"),

    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    postedAt: timestamp("posted_at", { withTimezone: true }), // when status became posted
    voidedAt: timestamp("voided_at", { withTimezone: true }),

    createdBy: uuid("created_by")
      .notNull()
      .references(() => users.id),
    postedBy: uuid("posted_by").references(() => users.id),
    voidedBy: uuid("voided_by").references(() => users.id),
  },
  (table) => [
    // Speeds up the duplicate-prevention lookup and the "invoices for this account"
    // view. It is a plain index, not a unique constraint: a voided monthly invoice
    // must not block a re-bill for the same period, so the guard lives in the
    // billing service where it can consider the invoice status.
    index("invoices_service_account_period_idx").on(
      table.serviceAccountId,
      table.billingPeriodYear,
      table.billingPeriodMonth
    ),
    // S1-3 / S12-2: the duplicate-billing guard as a DATABASE invariant rather
    // than a service-level convention. A service account may hold at most one
    // monthly invoice per period, but a VOIDED invoice must not block a re-bill
    // for the same period — hence the partial predicate. One-off invoices leave
    // the period columns null, and Postgres treats nulls as distinct, so they
    // never collide. The plain index above stays: it still serves the
    // status-aware lookup the billing service performs before inserting.
    uniqueIndex("invoices_service_account_period_uq")
      .on(table.serviceAccountId, table.billingPeriodYear, table.billingPeriodMonth)
      .where(sql`${table.status} <> 'void'`),
    // Phase 8's dashboard and Monthly Billing Summary read invoices by invoice date
    // for one calendar month, so the date is indexed on its own.
    index("invoices_invoice_date_idx").on(table.invoiceDate),
    // S1-10: the overdue list and the aging report both range-scan due_date.
    index("invoices_due_date_idx").on(table.dueDate),
    // S12-4: an invoice number looked up from a printed document or a receipt is
    // a substring search, so it needs the trigram index like the subscriber names.
    index("invoices_invoice_number_trgm_idx").using(
      "gin",
      sql`${table.invoiceNumber} gin_trgm_ops`
    ),
  ]
);

// ─── Invoice Line Items ───────────────────────────────────────────────────────
// An invoice can have several line items (subscription + late fee + …).
// They are for the printed document; the authoritative total is on the invoice row.
export const invoiceLineItems = pgTable("invoice_line_items", {
  id: uuid("id").primaryKey().defaultRandom(),
  invoiceId: uuid("invoice_id")
    .notNull()
    .references(() => invoices.id),

  description: varchar("description", { length: 200 }).notNull(),
  // e.g. "Fiber 25Mbps — January 2025", "Late Payment Fee", "Reconnection Fee"

  quantity: integer("quantity").notNull().default(1),
  unitAmountCentavos: integer("unit_amount_centavos").notNull(),
  totalAmountCentavos: integer("total_amount_centavos").notNull(),
});

// ─── Billing Run Log ──────────────────────────────────────────────────────────
// Records every time the monthly billing job ran — for audit and debugging.
export const billingRuns = pgTable("billing_runs", {
  id: uuid("id").primaryKey().defaultRandom(),

  billingPeriodYear: integer("billing_period_year").notNull(),
  billingPeriodMonth: integer("billing_period_month").notNull(),

  // Stats from the run
  totalServiceAccountsProcessed: integer("total_service_accounts_processed").notNull(),
  totalInvoicesGenerated: integer("total_invoices_generated").notNull(),
  totalInvoicesSkipped: integer("total_invoices_skipped").notNull(), // already had an invoice
  totalAmountBilledCentavos: integer("total_amount_billed_centavos").notNull(),

  status: varchar("status", { length: 20 }).notNull(), // "completed" | "failed" | "partial"
  errorDetails: text("error_details"),

  ranAt: timestamp("ran_at", { withTimezone: true }).notNull().defaultNow(),
  ranBy: uuid("ran_by")
    .notNull()
    .references(() => users.id),
});

// ─── Relations ───────────────────────────────────────────────────────────────
export const invoicesRelations = relations(invoices, ({ one, many }) => ({
  serviceAccount: one(serviceAccounts, {
    fields: [invoices.serviceAccountId],
    references: [serviceAccounts.id],
  }),
  lineItems: many(invoiceLineItems),
}));

export const invoiceLineItemsRelations = relations(invoiceLineItems, ({ one }) => ({
  invoice: one(invoices, {
    fields: [invoiceLineItems.invoiceId],
    references: [invoices.id],
  }),
}));

export const billingRunsRelations = relations(billingRuns, ({ one }) => ({
  ranByUser: one(users, {
    fields: [billingRuns.ranBy],
    references: [users.id],
  }),
}));

export type Invoice = typeof invoices.$inferSelect;
export type NewInvoice = typeof invoices.$inferInsert;
export type InvoiceLineItem = typeof invoiceLineItems.$inferSelect;
export type NewInvoiceLineItem = typeof invoiceLineItems.$inferInsert;
export type BillingRun = typeof billingRuns.$inferSelect;
export type NewBillingRun = typeof billingRuns.$inferInsert;
